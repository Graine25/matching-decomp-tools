"""packets for a batch of agents: a sample of unmatched functions of the game, each with
what is known of it.

    python -I tools/local/packets.py --name sample1 [--min 17] [--max 64] [--count 50]
                                     [--agents 2] [--seed 1] [--module code.bin]
    python -I tools/local/packets.py --name sample2 --list wheres.txt --agents 4   # these functions

writes build/us-v1.2/packets/<name>/agent_<n>.md (one file per agent: its functions, each
with its line of functions.csv, the bounds of its name (tools/bounds.py), the instructions
(match.py show) and Hex-Rays' C (tools/local/ida.py) as a reference of what it does) and
functions.txt (every <where> of the batch, with its agent). functions of one class go to
one agent, so two agents never write the same file.

a local helper: the packets hold the game's instructions and stay in build/.
"""
import argparse
import csv
import json
import random
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import bounds
import config

TARGET = tuple(config.OWN)
NOP = 0xE1A00000
ASSERT = (0xE3A03000, 0xE1A02003, 0xE1A01003, 0xE1A00003)     # the assert's four zero arguments
_images, _table, _headers = {}, None, None


def image(module):
    if module not in _images:
        _images[module] = config.Image(module)
    return _images[module]


def table():
    global _table
    if _table is None:
        with open(config.CONFIG / "functions.csv", encoding="utf-8", newline="") as f:
            _table = {(r["module"], int(r["start"], 16)): r for r in csv.DictReader(f)}
    return _table


def ready_classes():
    """the classes whose structure is proven: their header, or a base's (all the way up), written by
    a person and kept by tools/headers.py, and not a class tools/headers.py left without members."""
    parents = defaultdict(list)
    with open(config.CONFIG / "classes.csv", encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f):
            parents[r["class"]] = [b.rsplit(":", 1)[0] for b in r["bases"].split()]
    written = set()
    for h in (config.ROOT / "include").rglob("*.h"):
        if not h.read_text(encoding="utf-8", errors="replace").startswith("// generated by tools/headers.py"):
            written.add(h.relative_to(config.ROOT / "include").with_suffix("").as_posix().replace("/", "::").lower())
    empty = set()
    path = config.BUILD / "no_members.txt"
    if path.exists():
        empty = {line.split()[0] for line in path.read_text(encoding="utf-8").splitlines() if line.strip()}

    def proven(c, seen=()):
        if c.lower() in written:
            return True
        return any(proven(b, seen + (c,)) for b in parents.get(c, []) if b not in seen)
    return {c for c in set(parents) | {c for c in parents} if c not in empty and proven(c)}


def blocked(r):
    """why an agent of the small rows would stop on this function for sure, or None."""
    method, cls = r["method"], r["class"]
    short = cls.rsplit("::", 1)[-1] if cls else ""
    if method.startswith("~") or (short and method == short) or any(k in r["name"] for k in ("::~",)) \
            or (short and r["name"].endswith(f"{short}::{short}")):
        return "a constructor or destructor: needs the class's layout (the header row of AGENTS.md)"
    start, end = int(r["start"], 16), int(r["end"], 16)
    im = image(r["module"])
    words = [im.word(x) for x in range(start, end, 4)]
    for k, w in enumerate(words):
        if w != NOP:
            continue
        if k == len(words) - 1 or (k + 1 < len(words) and words[k + 1] >> 28 == 0xE and k + 1 == len(words)):
            continue                                            # the tail call to the next function
        if k >= 4 and tuple(words[k - 4:k]) == ASSERT:
            continue                                            # an assert: GFLassert
        return f"a call the linker removed at +{4 * k:#x} whose callee cannot be named"
    return None


def headers():
    """{address comment as headers write it: the declaration line}"""
    global _headers
    if _headers is None:
        import re
        _headers = {}
        for h in (config.ROOT / "include").rglob("*.h"):
            for line in h.read_text(encoding="utf-8", errors="replace").splitlines():
                for m in re.finditer(r"([\w.]+:[0-9A-F]{8})", line):
                    _headers.setdefault(m.group(1), (line.split("//")[0], h.relative_to(config.ROOT).as_posix()))
    return _headers


def declaration(r):
    found = headers().get(f"{r['module']}:{r['start']}")
    return f"{found[0].strip()}` in `{found[1]}" if found else None


def mangled_class(cls):
    return "".join(f"{len(p)}{p}" for p in cls.split("::"))


def class_header(cls):
    parts = cls.split("::")
    path = config.ROOT / "include" / Path(*parts[:-1], parts[-1] + ".h")
    return path if path.exists() else None


def symbol_hint(r):
    """what --sym is given: the start of the mangled name the source's definition makes. a
    function its header declares: _ZN<class><name>; a destructor's: D1 (complete) or D0
    (deleting); a secondary base's thunk of an override the header declares: _ZThn<n>_N..."""
    import re
    cls, slot = r["class"], r["slot"]
    if cls and re.fullmatch(r"[A-Za-z_]\w*(?:::[A-Za-z_]\w*)*", cls):
        mangled = mangled_class(cls)
        found = headers().get(f"{r['module']}:{r['start']}")
        name = None
        if found:
            m = re.search(r"(~?[A-Za-z_]\w*)\s*\(", found[0])
            name = m.group(1) if m else None
        header = class_header(cls)
        if name is None and slot in ("0", "1") and header and \
                re.search(r"virtual\s+~" + re.escape(cls.split("::")[-1]) + r"\s*\(", header.read_text(encoding="utf-8", errors="replace")):
            name = "~"
        if name:
            if slot.startswith("-"):
                at = slot[1:].split(":")[0]
                if not name.startswith("~"):
                    return f"_ZThn{at}_N{mangled}{len(name)}{name}"
            elif name.startswith("~"):
                return f"_ZN{mangled}" + ("D1Ev" if slot == "0" else "D0Ev")
            else:
                return f"_ZN{mangled}{len(name)}{name}"
    if r["method"] and r["class"]:
        return r["method"]
    return f"sub_{r['start']}" if r["module"] == "code.bin" else f"f_{r['module']}_{r['start']}"


_bases, _own = None, {}


def own_members(cls):
    """{offset: (type, name)} of the `// +0x..` lines of a class's own header."""
    import re
    if cls not in _own:
        found = {}
        header = class_header(cls)
        if header:
            text = header.read_text(encoding="utf-8", errors="replace")
            m = re.search(r"\b(?:class|struct)\s+" + re.escape(cls.split("::")[-1]) + r"\b[^;{]*\{", text)
            for line in (text[m.end():] if m else "").splitlines():
                mm = re.match(r"\s*(?P<decl>[^;/(){}=]+?);\s*//\s*\+0x(?P<off>[0-9a-fA-F]+)", line)
                if not mm or line.lstrip().startswith(("virtual", "static", "typedef", "enum")):
                    continue
                dm = re.match(r"(?P<type>.*?[\s*&])(?P<name>[A-Za-z_]\w*)(?:\[[^\]]*\])?$", mm.group("decl").strip())
                if dm and not dm.group("name").startswith("unk_"):
                    found[int(mm.group("off"), 16)] = (dm.group("type").strip(), dm.group("name"))
        _own[cls] = found
    return _own[cls]


def layout(cls, base=0, depth=0):
    """{offset: (type, name, the class that declares it)} of a class and its bases."""
    global _bases
    if _bases is None:
        _bases = {}
        with open(config.CONFIG / "classes.csv", encoding="utf-8", newline="") as f:
            for r in csv.DictReader(f):
                _bases.setdefault(r["class"], [(b.rsplit(":", 1)[0], int(b.rsplit(":", 1)[1]))
                                               for b in r["bases"].split() if ":" in b])
    out = {}
    if depth > 8:
        return out
    for b, off in _bases.get(cls, []):
        out.update(layout(b, base + off, depth + 1))
    for off, (t, n) in own_members(cls).items():
        out[base + off] = (t, n, cls)
    return out


def offsets_used(r):
    """the offsets the function loads and stores through `this` (tools/fields.py's walk: this in
    r0, followed through copies and `add`), or set() when it cannot be followed."""
    import fields
    start, end = int(r["start"], 16), int(r["end"], 16)
    if r["mode"] != "arm" or r["slot"].startswith("-"):
        return set()                    # a thunk: this is adjusted first
    got = fields.accesses(image(r["module"]), start, end)
    return {off for off, _, _ in got[0]} if got else set()


def members_used(r):
    """the members of the function's class (its bases' included) at the offsets it uses."""
    cls = r["class"]
    if not cls:
        return []
    flat = layout(cls)
    return [f"+{off:#x} `{t} {n}` ({owner})" for off in sorted(offsets_used(r)) if off in flat
            for t, n, owner in [flat[off]]]


def callees(r):
    """the functions it calls, with the game's name or ours, and their declaration if a header has one."""
    start, end = int(r["start"], 16), int(r["end"], 16)
    im = image(r["module"])
    out, seen = [], set()
    for x in range(start, end, 4):
        w = im.word(x)
        if (w & 0x0E000000) != 0x0A000000 or w >> 28 == 0xF:
            continue
        off = w & 0xFFFFFF
        t = x + 8 + 4 * (off - 0x1000000 if off & 0x800000 else off)
        if start <= t < end or t in seen:
            continue
        seen.add(t)
        row = table().get((r["module"], t))
        if row is None or row["kind"] == "stub":
            continue
        name = row["name"] or (f"sub_{t:08X}" if r["module"] == "code.bin" else f"f_{r['module']}_{t:08X}")
        decl = headers().get(f"{r['module']}:{t:08X}")
        out.append(f"{t:08X} {name}" + (f" (declared `{decl[0].strip()}`)" if decl else ""))
    return out[:8]


def reference_c(rows, listed, out):
    """{(module, start): (decompiler, C)} of the batch's functions, with the project's types
    first (tools/typecontext.py): Hex-Rays' when the IDA databases are there (local/ida.py),
    else Ghidra's (local/ghidra_server.py, its server running), else none."""
    import json
    import typecontext
    types = out / "types"
    types.mkdir(parents=True, exist_ok=True)
    context = typecontext.program_context(listed.read_text(encoding="utf-8").split())
    for module, ctx in context.items():
        (types / f"{module.replace('.', '_')}.json").write_text(json.dumps(ctx), encoding="utf-8")
    found = {}
    databases = config.PATHS.get("ida_databases")
    if databases and any(Path(databases).glob("*.i64")):
        ida = out / "ida"
        r = subprocess.run(["py", "-3.12", str(Path(__file__).with_name("ida.py")), "c", "--types", str(types),
                            "--out", str(ida), f"@{listed}"], capture_output=True, text=True)
        if r.returncode:
            print("ida.py failed:", r.stderr.strip()[-300:])
        for r_ in rows:
            c = ida / f"{r_['module'].replace('.', '_')}_{int(r_['start'], 16):08X}.c"
            if c.exists():
                found[(r_["module"], int(r_["start"], 16))] = ("Hex-Rays", c.read_text(encoding="utf-8"))
        if found:
            return found
    # Ghidra: one request per program to the server
    server = Path(__file__).with_name("ghidra_server.py")
    by_module = defaultdict(list)
    for r_ in rows:
        by_module[r_["module"]].append(int(r_["start"], 16))
    for module, starts in sorted(by_module.items()):
        ctx = types / f"{module.replace('.', '_')}.json"
        if not ctx.exists():
            continue
        r = subprocess.run([sys.executable, "-I", str(server), "typed", str(ctx)] + [f"{s_:X}" for s_ in starts],
                           capture_output=True, text=True)
        if r.returncode or "=== " not in r.stdout:
            print("no Ghidra server, or it failed: packets go without a decompiler's C:",
                  (r.stderr or r.stdout).strip()[-200:])
            break
        for chunk in r.stdout.split("=== ")[1:]:
            head, _, body = chunk.partition("\n")
            mod, _, addr = head.strip().rpartition(":")
            found[(mod or "code.bin", int(addr, 16))] = ("Ghidra", body)
    return found


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--name", required=True)
    p.add_argument("--min", type=int, default=17)
    p.add_argument("--max", type=int, default=64)
    p.add_argument("--count", type=int, default=50)
    p.add_argument("--agents", type=int, default=2)
    p.add_argument("--seed", type=int, default=1)
    p.add_argument("--module")
    p.add_argument("--list", help="a file of <where>, one a line: these functions instead of a sample")
    p.add_argument("--decompiler", action="store_true",
                   help="add a decompiler's C (Hex-Rays, else Ghidra, with the project's types): off by default, "
                        "two A/B batches of 2026-11-12 found it no help to Haiku on small functions")
    p.add_argument("--m2c", action="store_true",
                   help="add m2c's C (local/m2cref.py) to each function: off by default, an A/B batch of "
                        "2026-11-12 found it no help to Haiku and two forced sources where it was given")
    p.add_argument("--ready", action="store_true",
                   help="only functions of classes that are ready: built on a header a person wrote (theirs or a base's)")
    a = p.parse_args()

    matched = set()
    report = config.BUILD / "report.json"
    if report.exists():
        for r in json.loads(report.read_text(encoding="utf-8")):
            module, _, off = r["where"].rpartition(":")
            matched.add((module or "code.bin", int(off, 16)))        # any source counts: no second try here
    with open(config.CONFIG / "functions.csv", encoding="utf-8", newline="") as f:
        rows = [r for r in csv.DictReader(f)
                if r["kind"] not in ("stub", "lib") and r["mode"] == "arm"
                and r["library"].rstrip("?") in TARGET
                and a.min <= int(r["end"], 16) - int(r["start"], 16) <= a.max
                and (r["module"], int(r["start"], 16)) not in matched
                and (not a.module or r["module"] == a.module)]
    if a.list:
        wanted = set()
        for w in Path(a.list).read_text(encoding="utf-8").split():
            module, _, addr = w.rpartition(":")
            wanted.add((module or "code.bin", int(addr, 16)))
        with open(config.CONFIG / "functions.csv", encoding="utf-8", newline="") as f:
            rows = [r for r in csv.DictReader(f) if (r["module"], int(r["start"], 16)) in wanted]
    else:
        if a.ready:
            ready = ready_classes()
            rows = [r for r in rows if r["class"] in ready]
            print(f"{len(rows)} functions of ready classes ({len(ready)} classes)")
        random.Random(a.seed).shuffle(rows)
        # what an agent would stop on for sure is not offered (batch1, batch2: 38 of 100 got no
        # source that compiles): kept in skipped.txt with the reason
        kept, skipped = [], []
        for r in rows:
            why = blocked(r)
            (skipped if why else kept).append((r, why))
        rows = [r for r, _ in kept][:a.count]
        skipped_rows = skipped
    else_skipped = locals().get("skipped_rows", [])
    scopes = bounds.load()

    def where(r):
        return f"0x{r['start']}" if r["module"] == "code.bin" else f"{r['module']}:0x{r['start']}"

    def owner(r):
        scope = scopes.get(int(r["start"], 16), {}).get("scope", "") if r["module"] == "code.bin" else ""
        return r["class"] or scope

    # one class, one agent
    groups = defaultdict(list)
    for r in rows:
        groups[(r["module"], owner(r)) if owner(r) else (r["module"], r["start"])].append(r)
    agents = [[] for _ in range(a.agents)]
    for group in sorted(groups.values(), key=len, reverse=True):
        min(agents, key=len).extend(group)

    out = config.BUILD / "packets" / a.name
    out.mkdir(parents=True, exist_ok=True)
    if else_skipped:
        (out / "skipped.txt").write_text("".join(f"{where(r)} {why}\n" for r, why in else_skipped), encoding="utf-8")
        reasons = defaultdict(int)
        for _, why in else_skipped:
            reasons[why.split(":")[0]] += 1
        print("not offered:", dict(reasons))
    listed = out / "list.txt"
    listed.write_text("\n".join(where(r).replace("0x", "0x") for r in rows) + "\n", encoding="utf-8")
    decompiled = reference_c(rows, listed, out) if a.decompiler else {}

    lines = []
    for n, funcs in enumerate(agents, 1):
        text = [f"# Batch {a.name}, agent {n}: {len(funcs)} functions", ""]
        for r in funcs:
            w, start = where(r), int(r["start"], 16)
            size = int(r["end"], 16) - start
            text += [f"## {w}  ({size} bytes)", ""]
            known = [f"- {k}: {r[k]}" for k in ("name", "class", "slot", "method", "library") if r[k]]
            b = scopes.get(start) if r["module"] == "code.bin" else None
            if b:
                if b["scope"]:
                    known.append(f"- scope (from the order of the names): {b['scope']}" + (", a const member function" if b["const"] else ""))
                known.append(f"- its mangled name is between `{b['after']}` and `{b['before']}`")
            cls = owner(r)
            if cls:
                parts = cls.split("::")
                for k in range(len(parts), 0, -1):       # a nested class is in its outer class's header
                    header = Path(*parts[:k]).with_suffix(".h")
                    if (config.ROOT / "include" / header).exists():
                        known.append(f"- header: include/{header.as_posix()}")
                        break
            declared = declaration(r)
            if declared:
                known.append(f"- declared: `{declared.strip()}`")
            if r["slot"].startswith("-"):
                known.append("- a thunk of a secondary base's vtable: write the override the header declares "
                             "(the line above); the compiler makes this thunk from it, with this `//!` line")
            used = members_used(r)
            if used:
                known.append("- members it reads or writes through this (its class's and its bases', in "
                             "the headers): " + "; ".join(used))
            known.append(f"- the `//!` line: `//! {w} {symbol_hint(r)}` (the symbol: what you pass to --sym)")
            called = callees(r)
            if called:
                known.append("- it calls: " + "; ".join(called))
            text += known + [""]
            shown = subprocess.run([sys.executable, "-I", str(config.ROOT / "tools" / "match.py"), "show", w],
                                   capture_output=True, text=True, cwd=config.ROOT)
            text += ["```", shown.stdout.rstrip(), "```", ""]
            # a function whose code is not the same in the other versions: show theirs too
            for version in config.GAME_VERSIONS:
                if version != config.MAIN and config.Image(r["module"], version).status(start) == "differs":
                    other = subprocess.run([sys.executable, "-I", str(config.ROOT / "tools" / "match.py"), "show", w],
                                           capture_output=True, text=True, cwd=config.ROOT,
                                           env=dict(__import__("os").environ, MATCH_VERSION=version))
                    text += [f"Not the same code in {version} (AGENTS.md, \"Versions\"): check with "
                             f"`MATCH_VERSION={version}` too.", "```", other.stdout.rstrip(), "```", ""]
            found = decompiled.get((r["module"], start))
            if found:
                text += [f"{found[0]} (a reference of what it does, not a draft):", "```c", found[1].rstrip(), "```", ""]
            if a.m2c and r["mode"] == "arm":
                try:
                    sys.path.insert(0, str(Path(__file__).resolve().parent))
                    import m2cref                       # m2c, run as an outside program (GPL-3.0)
                    ref = m2cref.reference(w)
                    if ref and "error" not in ref.lower()[:200]:
                        text += ["m2c (a reference of what it does, not a draft):", "```c", ref, "```", ""]
                except Exception:
                    pass
            lines.append(f"{w} agent_{n}")
        (out / f"agent_{n}.md").write_text("\n".join(text), encoding="utf-8", newline="\n")
        print(f"agent_{n}.md: {len(funcs)} functions, {len(chr(10).join(text))} characters")
    (out / "functions.txt").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(rows)} functions in {out}")


if __name__ == "__main__":
    main()
