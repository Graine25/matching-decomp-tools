"""writes a header skeleton for each class the game names.

  python -I tools/headers.py [--check]

from classes.csv, vtables.csv and the slot names of tools/classify.py: one
file per class, include/<namespace>/.../<Class>.h, with its bases and its
virtual functions in the order of its vtable, so that a call through the
class lands on the right slot. what the game does not say is a placeholder:

- a virtual function without a known name is vfN (N its slot);
- parameters are real where the game says them: a slot that some class
  exports or imports by its mangled name has that name's parameter types,
  for the whole hierarchy (needs llvm-cxxfilt). they are written when every
  type can be declared (built-in types, pointers and references to classes
  outside any class); else they stay in a comment. the return type is never
  in a mangled name: it is `void` until someone writes the function;
- a member function the game exports by name is declared with its parameters, when every
  type can be declared; whether it is static is not in a name. a class the game has no
  type information for, but whose exports show it is a class (a constructor, a
  destructor, a const member function), gets a header with those declarations;
- a return type is never in a name. a function that only loads a member and returns
  (`ldrb r0, [r0, #n]; bx lr`), or returns a constant, shows its width: u8, s16, u32, bool
  for 0 or 1 and for a byte of an Is.../Has... function, a pointer to the class X for a
  GetX when exactly one class is called X. for a virtual function every class's version of
  the slot must agree. marked as guesses. config/<version>/returns.csv overrides them:
  key (the mangled name, or Class#slot for a virtual function), type, evidence;
- a type that some exported name has behind a pointer or reference is a class, even with
  nothing else known of it: it gets a header, and the classes nested in it go there; unless
  it is also passed by value and nothing makes it a class: then it is an enum;
- an enum (tools/enums.py, config/<version>/enums.csv: a named type passed by value that is
  not a class) is written with the size its callers show, by two placeholder values (the
  real ones are not known): inside its class when its name is in a class (with any scope
  between as a struct), else in a header of its own, include/<namespace>/.../<Enum>.h.
  parameters of that type, by value or not, are then declared;
- a member function that its code does not show the return of takes the one its callers
  show (tools/callers.py, config/<version>/calls.csv), marked as a guess from them;
- a return type from returns.csv that names a class is declared ahead (a class nested in
  another cannot be), one that names an enum brings its header: a struct returned by value
  is written there like any type;
- data members come from tools/fields.py and from config/<version>/members.csv (members a
  person gives, with the evidence; they win at their offset) (config/<version>/fields.csv: what the
  class's functions read and write through `this`): `field_<offset>` with the
  width seen, `unk_<offset>` for the bytes between that nothing was seen to
  use. names and exact types are guesses, and say so. every member's offset is
  then checked with the compiler (offsetof); a class whose members do not land
  where they were seen gets none (build/<version>/no_members.txt says why, for
  each). a second base's offset is in a comment;
- a base that some class has another base right after (the RTTI gives each base's
  offset) is at least that long: the compiler puts the next base where the first
  one's data ends, so the first one gets `unk_` bytes up to there when the members
  seen in it end sooner.

a generated file starts with the line `// generated by tools/headers.py`.
remove that line when you edit a header: the tool rewrites only files that
still have it, and never touches the others. --check compiles every header
with the compiler.

a class nested in a class (app::tool::ButtonManager::IButtonCallback) is written
inside its outer class, in the outer class's header, before the outer class's
own members. it is left out when that would make two headers need each other
(the nested class derives from something that derives from the outer one).

skipped, and listed at the end: templates and other names that are not plain,
nested classes left out, classes of anonymous namespaces.
"""
