MARK = "// generated by tools/headers.py"
MEMBER = {(1, "u"): "u8", (1, "s"): "s8", (2, "u"): "u16", (2, "s"): "s16", (4, "u"): "u32", (4, "s"): "s32",
          (4, "f"): "f32", (4, "p"): "void *", (8, "f"): "f64"}
IDENT = re.compile(r"[A-Za-z_]\w*$")
KEYWORDS = {"delete", "new", "operator", "class", "this", "template", "default", "switch", "register", "union", "export"}


BUILTIN = {"void", "bool", "char", "signed char", "unsigned char", "short", "unsigned short", "int", "unsigned int",
           "long", "unsigned long", "long long", "unsigned long long", "float", "double", "wchar_t",
           "u8", "s8", "u16", "s16", "u32", "s32", "u64", "s64", "f32", "f64"}   # and types.h's


def demangle(names):
    """{mangled: demangled} by llvm-cxxfilt; empty when it is not installed."""
    exe = shutil.which("llvm-cxxfilt") or r"C:\Program Files\LLVM\bin\llvm-cxxfilt.exe"
    if not Path(exe).exists() and not shutil.which("llvm-cxxfilt"):
        print("llvm-cxxfilt not found: no parameter types")
        return {}
    names = sorted(names)
    r = subprocess.run([exe], input="\n".join(names) + "\n", capture_output=True, text=True)
    return dict(zip(names, r.stdout.split("\n")))


def signature(demangled):
    """(parameter types, const) of a demangled function, or None."""
    if not demangled.endswith(")") and not demangled.endswith(") const"):
        return None
    const = demangled.endswith(" const")
    text = demangled[:-6] if const else demangled
    depth, i = 0, len(text) - 1
    while i >= 0:
        depth += text[i] == ")"
        depth -= text[i] == "("
        if depth == 0:
            break
        i -= 1
    inner, params, depth, start = text[i + 1:-1], [], 0, 0
    for j, c in enumerate(inner):
        depth += c in "(<"
        depth -= c in ")>"
        if c == "," and depth == 0:
            params.append(inner[start:j].strip())
            start = j + 1
    if inner.strip():
        params.append(inner[start:].strip())
    return tuple(params), const


def type_name(param):
    """(the named type of a parameter or None for a built-in one, whether it is behind a
    pointer or reference), or None when the type is not a plain one."""
    if any(c in param for c in "<>()[]"):
        return None
    indirect = "*" in param or "&" in param
    base = re.sub(r"\bconst\b|\bvolatile\b|[*&]", " ", param)
    base = " ".join(base.split())
    if base in BUILTIN:
        return None, indirect
    if re.fullmatch(r"[A-Za-z_]\w*(?:::[A-Za-z_]\w*)*", base):
        return base, indirect
    return None


def check_headers(out_root, paths, emitted, classes, extra=()):
    """compiles every header, in batches side by side, with an offsetof check for every
    member written. gives the classes with a member that is not at its offset (or whose
    header does not compile), the classes whose virtual functions' guessed return types an
    override disagrees with, and the error lines left."""
    exe, env = config.compiler(config.DEFAULT_CC)
    todo = sorted(classes)
    batches = [todo[n:n + 150] for n in range(0, len(todo), 150)] or [[]]

    def run(job):
        k, batch = job
        lines, owner = ["#include <stddef.h>"], {}
        if k == 0:
            lines += [f'#include "{h.as_posix()}"' for h in extra]
        for c in batch:
            lines.append(f'#include "{paths[c].as_posix()}"')
        for i, c in enumerate(batch):
            for off in emitted.get(c, ()):
                lines.append(f"typedef char member_check_{i}_{off:X}[offsetof(::{c}, field_{off:X}) == {off:#x} ? 1 : -1];")
                owner[len(lines)] = c
        src = Path(tmp) / f"batch{k}.cpp"
        src.write_text("\n".join(lines) + "\n", encoding="utf-8")
        r = subprocess.run([str(exe), "-c", "--cpp", "--gnu", *config.DEFAULT_FLAGS.split(), "-I", str(out_root), str(src),
                            "-o", str(Path(tmp) / f"batch{k}.o")], env=env, capture_output=True, text=True)
        return batch, owner, src.name, r.returncode, r.stdout + r.stderr

    bad, clash, errors = set(), set(), []
    with tempfile.TemporaryDirectory() as tmp:
        with ThreadPoolExecutor(max_workers=max(2, (os.cpu_count() or 4) - 2)) as pool:
            results = list(pool.map(run, enumerate(batches)))
    for batch, owner, name, code, log in results:
        with_members = {c for c in batch if emitted.get(c)}
        if code and not re.search(r'", line \d+: Error', log):
            bad |= with_members                     # it failed some other way: none of these is checked
            errors.append(log.strip().splitlines()[0] if log.strip() else f"{name}: the compiler failed")
        for line in log.splitlines():
            found = re.match(r'"([^"]+)", line (\d+): Error', line)
            if not found:
                continue
            overridden = re.search(r'#317: .*overridden virtual function "(.+)::[^:"]+"', line)
            if overridden:
                clash.add(overridden.group(1))
            elif Path(found.group(1)).name == name and int(found.group(2)) in owner:
                bad.add(owner[int(found.group(2))])
            else:
                where = Path(found.group(1)).as_posix()
                hit = {c for c in with_members if where.endswith(paths[c].as_posix())}
                bad |= hit
                if not hit:
                    errors.append(line)
    return bad, clash, errors


def main():
    config.options(__doc__, "--check")
    m = classify.load(interfaces=True)
    # an interface whose vtable no table has, first base of a class with another base after it:
    # the game puts its vtable pointer at +0 (the class's secondary vtables say so), so it has
    # virtual functions; at least its destructor (the derived class's slots 0 and 1 are)
    lone_first = set()
    second_bases = {b for bases in m.parents.values() for b, at in bases if at > 0}
    for d, bases in m.parents.items():
        ordered = sorted(bases, key=lambda b: b[1])
        if d in m.primary and len(ordered) >= 2 and ordered[0][1] == 0 and ordered[1][1] > 0:
            b0 = ordered[0][0]
            if b0 not in m.primary and not m.parents.get(b0):
                lone_first.add(b0)
    members = fieldslib.load()
    # members a person gives (config/<version>/members.csv: class, offset (hex), width, type as
    # fields.csv's, of, evidence): they take the place of what fields.py found at that offset
    manual_why = {}
    manual_path = config.CONFIG / "members.csv"
    if manual_path.exists():
        with open(manual_path, encoding="utf-8", newline="") as f:
            for r in csv.DictReader(f):
                cls, off = r["class"], int(r["offset"], 16)
                members[cls] = [e for e in members.get(cls, []) if e[0] != off] + \
                    [(off, int(r["width"]), r["type"], 0, r.get("of") or "")]
                manual_why[(cls, off)] = r["evidence"]
    from_exports = fieldslib.named_classes(m.parents)
    static = crolib.Cro(config.ORIG / "romfs" / "static.crs").exports()
    mangled_at = {addr: name for name, addr in static.items()}
    pretty = demangle(set(static) | {name for _, slots in m.primary.values() for _, name in slots if name.startswith("_Z")})
    pointed = set()                     # types behind a pointer or reference in an exported name: classes
    for mangled in static:
        sig = signature(pretty.get(mangled, "")) if mangled.startswith("_Z") else None
        for param in sig[0] if sig else ():
            t = type_name(param)
            if t and t[0] and t[1]:
                pointed.add(t[0])
    enum_info = enumlib.load()
    classes = set(m.parents) | from_exports | (pointed - set(enum_info))
    plain = {c for c in classes if all(IDENT.match(p) for p in c.split("::")) and "_GLOBAL__N_" not in c
             and not re.match(r"(?:N|ZN|Z)K?\d|N?St\d|N?St[A-Z]", c)}
    nested = {c for c in plain if any("::".join(c.split("::")[:i]) in classes for i in range(1, c.count("::") + 1))}
    top_level = plain - nested
    usable = set(top_level)
    # nested classes: each goes in the header of the class it is in, if no header then needs itself
    header_of = {c: c for c in top_level}
    needs = {c: {b for b, _ in m.parents.get(c, []) if b in top_level} for c in top_level}
    inside_of = {}

    def reaches(a, b, seen=None):
        seen = seen if seen is not None else set()
        if a == b:
            return True
        if a in seen:
            return False
        seen.add(a)
        return any(reaches(n, b, seen) for n in needs.get(a, ()))

    written_by_person = {}

    def hand_written(c):
        """whether the class's header is a person's (remembered: what this tool writes starts
        with its mark, so the answer does not change during a run)."""
        if c not in written_by_person:
            parts = c.split("::")
            path = config.ROOT / "include" / Path(*parts[:-1], parts[-1] + ".h")
            try:
                with open(path, encoding="utf-8", errors="replace") as f:
                    written_by_person[c] = not f.read(len(MARK)).startswith(MARK)
            except OSError:
                written_by_person[c] = False
        return written_by_person[c]

    # the slots a person declared in a header of theirs (a `// slot N` on the line): the classes
    # built on it take that name, those parameters and that return, so that they override it
    slot_line = re.compile(r"virtual\s+(?P<ret>[\w:<>\s\*&]*?)\s*\b(?P<name>\w+)\s*\((?P<params>[^()]*)\)\s*"
                           r"(?P<const>const)?\s*(?:=\s*0\s*)?(?:\{[^{}\n]*\}|;)[^\n]*?//[^\n]*?\bslot\s+(?P<slot>\d+)")
    declared_slots = {}
    override_cache = {}

    def class_body(text, short):
        """the braced body of `class <short>` in text, its nested classes cut out, or None."""
        m_ = re.search(r"\b(?:class|struct)\s+" + re.escape(short) + r"\b[^;{]*\{", text)
        if not m_:
            return None
        depth, i = 0, m_.end() - 1
        for j in range(i, len(text)):
            depth += text[j] == "{"
            depth -= text[j] == "}"
            if depth == 0:
                return text[i:j + 1]
        return None

    def person_slots(c, any_header=False):
        """{slot: (name, parameters, return, const)} of a class whose header a person wrote (or, with
        any_header, whatever wrote it: the slots as its header on disk declares them)."""
        key = (c, any_header)
        if key in declared_slots:
            return declared_slots[key]
        declared_slots[key] = {}
        top = header_of.get(c)
        if top is None or (not any_header and not hand_written(top)):
            return declared_slots[key]
        parts = top.split("::")
        text = (config.ROOT / "include" / Path(*parts[:-1], parts[-1] + ".h")).read_text(encoding="utf-8", errors="replace")
        body = class_body(text, parts[-1])
        for inner in c.split("::")[len(parts):]:
            body = class_body(body, inner) if body else None
        if not body:
            return declared_slots[key]
        own = body[1:]
        for inner in re.finditer(r"\b(?:class|struct)\s+\w+[^;{]*\{", body[1:]):
            nested = class_body(body[1:][inner.start():], re.search(r"(?:class|struct)\s+(\w+)", inner.group(0)).group(1))
            if nested:
                own = own.replace(nested, "")
        # a type the header declares outside the class (an enum of the namespace) is written
        # with its namespace, for the classes of other namespaces built on it
        ns = top.rsplit("::", 1)[0] if "::" in top else ""
        outside = {n for n in re.findall(r"\b(?:enum|class|struct)\s+(\w+)", text.replace(body, ""))} - {parts[-1]}

        def qualify(t):
            for n in outside:
                t = re.sub(r"(?<![\w:])" + re.escape(n) + r"\b", f"::{ns}::{n}" if ns else f"::{n}", t)
            return t
        for m_ in slot_line.finditer(own):
            declared_slots[key][int(m_.group("slot"))] = (m_.group("name"), qualify(m_.group("params").strip()),
                                                          qualify(" ".join(m_.group("ret").split())), bool(m_.group("const")))
        return declared_slots[key]

    def person_slot(c, i):
        """the slot i as a person declared it in c or in the bases it shares its vtable with."""
        while c is not None and c in header_of:         # through the bases the headers write only
            if hand_written(header_of[c]) and i in person_slots(c):
                return c, person_slots(c)[i]
            c = next((b for b, off in m.parents.get(c, []) if off == 0), None)
        return None

    waiting = sorted(nested, key=lambda c: (c.count("::"), c))
    moved = True
    while moved:                        # a nested class after the nested classes it derives from
        moved, later = False, []
        for c in waiting:
            outer = c.rsplit("::", 1)[0]
            parents_of = [b for b, _ in m.parents.get(c, [])]
            if outer in nested and outer not in usable and outer in waiting:
                later.append(c)
                continue
            if any(b in nested and b not in usable and b in waiting and b != c for b in parents_of):
                later.append(c)
                continue
            moved = True
            if outer not in usable or hand_written(header_of[outer]):
                continue                # no outer class to put it in, or a header a person wrote
            home = header_of[outer]
            if any(b == outer or (header_of.get(b) == home and b not in inside_of.get(outer, [])) for b in parents_of):
                continue                # derives from its outer class, or from a class of this header not complete there
            wanted = {header_of[b] for b in parents_of if b in usable}
            if any(reaches(h, home) for h in wanted if h != home):
                continue
            usable.add(c)
            header_of[c] = home
            needs[home] |= wanted - {home}
            inside_of.setdefault(outer, []).append(c)
        waiting = later
    function_of = {}
    thunks = {}                         # class -> {(offset of the base, slot): where}
    for r in m.rows:
        function_of[(r["module"], int(r["start"], 16))] = r
        t = re.fullmatch(r"-(\d+):(\d+)", r["slot"] or "")
        if t and r["class"]:
            thunks.setdefault(r["class"], {}).setdefault((int(t.group(1)), int(t.group(2))), f"{r['module']}:{r['start']}")

    # each enum: (the class it is in or None, the scopes between, its own header or None)
    enum_home = {}
    for e in sorted(enum_info):
        parts = e.split("::")
        if not all(IDENT.match(x) and x not in KEYWORDS for x in parts):
            continue
        outer = next(("::".join(parts[:k]) for k in range(len(parts) - 1, 0, -1) if "::".join(parts[:k]) in classes), None)
        if outer is not None:
            if outer in usable:
                enum_home[e] = (outer, parts[outer.count("::") + 1:-1], None)
        else:
            enum_home[e] = (None, parts[:-1], Path(*parts[:-1], parts[-1] + ".h"))
    enums_in = {}
    for e, (outer, middle, _) in enum_home.items():
        if outer is not None:
            enums_in.setdefault(outer, []).append(e)

    def enum_text(e):
        size, signed, seen = enum_info[e]
        why = ("its callers narrow it so (tools/enums.py)" if seen else
               "a guess: no caller shows it, the smallest that holds the constants passed")
        return [f"// {size} byte{'s' if size > 1 else ''}, {'signed' if signed else 'unsigned'}: {why}. "
                f"the values are placeholders that give it that size",
                enumlib.definition(e, size, signed)]

    def enum_block(cls):
        """the lines of the enums inside a class, the scopes between as structs."""
        tree = {}
        for e in sorted(enums_in.get(cls, [])):
            node = tree
            for scope in enum_home[e][1]:
                node = node.setdefault(scope, {})
            node.setdefault(None, []).append(e)

        def emit(node, indent):
            out = []
            for e in node.get(None, []):
                out += [indent + line for line in enum_text(e)]
            for scope in sorted(k for k in node if k is not None):
                out.append(f"{indent}struct {scope} {{  // a scope the game's names show, a guess")
                out += emit(node[scope], indent + "    ")
                out.append(f"{indent}}};")
            return out
        return emit(tree, "    ")

    def type_needs(name, home, cls=None):
        """what the header home needs to name a type in class cls: ('ahead', class), ('include',
        path or class), ('none',) when nothing is needed, or None when it cannot be named there.
        an enum in a class, or a class nested in one, comes with that class's header; in the
        same header it is defined before the outer class's own members (not before those of
        the classes nested with it)."""
        def from_header(h, owner):
            if h == home:
                return ("none",) if cls in (home, owner) else None
            if home is None or reaches(h, home):
                return None
            needs.setdefault(home, set()).add(h)
            return "include", h
        if name in enum_home:
            outer, _, own = enum_home[name]
            if outer is None:
                return "include", own
            return from_header(header_of[outer], outer)
        if name in enum_info:
            return None                         # an enum that has no place here
        if name in spaces:
            return None
        if any("::".join(name.split("::")[:i]) in inside for i in range(1, name.count("::") + 1)):
            if name not in usable:
                return None                     # nested in a class, and not written there
            return from_header(header_of[name], name)
        return "ahead", name

    # the parameter types of each slot, from the mangled names the game has for it
    with open(config.CONFIG / "signatures.csv", "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(("address", "mangled", "demangled"))
        for name, addr in sorted(static.items(), key=lambda kv: kv[1]):
            w.writerow((f"{addr:08X}", name, pretty.get(name, "")))
    votes = {}
    for cls, (module, slots) in m.primary.items():
        for i, (target, name) in enumerate(slots):
            where = m.target_function(target)
            mangled = name if name.startswith("_Z") else mangled_at.get(where[1]) if where and where[0] == "code.bin" else None
            sig = signature(pretty[mangled]) if mangled in pretty and "::~" not in pretty[mangled] else None
            if sig:
                votes.setdefault((m.introducer(cls, i), i), Counter())[sig] += 1
    slot_sig = {key: c.most_common(1)[0][0] for key, c in votes.items()}
    # a type can be declared ahead when it is a class outside any class
    # the member functions the game exports, by class: (name, parameters and const, mangled, address)
    exported = {}
    for mangled, addr in static.items():
        d = pretty.get(mangled, "")
        sig = signature(d) if mangled.startswith("_ZN") else None
        if not sig or "<" in d or "operator" in d:
            continue
        qualified = d[:len(d) - (6 if sig[1] else 0)]
        depth, i = 0, len(qualified) - 1
        while i >= 0:
            depth += qualified[i] == ")"
            depth -= qualified[i] == "("
            if depth == 0:
                break
            i -= 1
        cls, _, last = qualified[:i].rpartition("::")
        if cls in classes:
            exported.setdefault(cls, []).append((last, sig, mangled, addr & ~1))
    from_callers = {}                   # tools/callers.py: what the callers do with the result
    if (config.CONFIG / "calls.csv").exists():
        with open(config.CONFIG / "calls.csv", encoding="utf-8", newline="") as f:
            from_callers = {r["mangled"]: (r["type"], r["why"]) for r in csv.DictReader(f) if r["type"]}
    returns = {}
    returns_path = config.CONFIG / "returns.csv"
    if returns_path.exists():
        with open(returns_path, encoding="utf-8", newline="") as f:
            returns = {r["key"]: r["type"] for r in csv.DictReader(f) if r.get("key") and r.get("type")}
    named = {type_name(p)[0] for params, _ in slot_sig.values() for p in params if type_name(p) and type_name(p)[0]}
    named |= {type_name(p)[0] for funcs in exported.values() for _, (params, _), _, _ in funcs for p in params
              if type_name(p) and type_name(p)[0]}
    spaces = {"::".join(t.split("::")[:i]) for t in named | classes for i in range(1, t.count("::") + 1)} - classes

    # what a function returns, where its code shows it: (type as written, class to declare ahead)
    images = {}
