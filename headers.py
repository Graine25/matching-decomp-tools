                    writes_r0 = ((w & 0x0E000000) == 0x0A000000 and w & 0x01000000) \
                        or (w & 0x0FFFFFF0) == 0x012FFF30 \
                        or ((w & 0x0C000000) == 0x00000000 and (w >> 12) & 0xF == 0
                            and not (0x8 <= (w >> 21) & 0xF <= 0xB and w & 0x00100000)) \
                        or ((w & 0x0C100000) == 0x04100000 and (w >> 12) & 0xF == 0)
